"""
chain_test_generator.py — Generate pytest chain test files

Takes EndpointChain objects from ChainDetector and produces pytest code
that calls endpoints in sequence, threading captured values between steps.

Public API:

    generator = ChainTestGenerator()
    code = generator.generate_chain_file(chains, base_url="https://api.example.com")
"""

from __future__ import annotations

import re
from typing import Any, Dict, List, Optional

from chain_detector import ChainStep, EndpointChain
from spec_ingestion import EndpointSpec


class ChainTestGenerator:
    """
    Generates pytest test files for endpoint chains.

    Each chain becomes one test function. Steps are sequential calls with
    captured values threaded forward through local variables.
    """

    def generate_chain_file(
        self,
        chains: List[EndpointChain],
        base_url: str = '',
        spec_title: str = 'API',
    ) -> str:
        """
        Generate a complete pytest file for a list of chains.

        Args:
            chains:     Chains from ChainDetector.detect_chains().
            base_url:   API base URL from the spec (used as default in file header).
            spec_title: Spec title for the module docstring.

        Returns:
            Complete Python source as a string. Empty string if no chains.
        """
        if not chains:
            return ''

        parts = [self._file_header(base_url, spec_title)]
        for chain in chains:
            parts.append(self._generate_chain_test(chain))

        return '\n'.join(parts)

    # ── Private ───────────────────────────────────────────────────────────────

    def _file_header(self, base_url: str, title: str) -> str:
        fallback = base_url or 'http://localhost:8000'
        return (
            f'"""\n'
            f'Chain integration tests for {title}\n'
            f'Generated by AI Testing Agent — multi-endpoint test flows.\n'
            f'\n'
            f'Each test calls a sequence of endpoints and threads captured\n'
            f'values (ids, tokens) between steps.\n'
            f'"""\n'
            f'import pytest\n'
            f'import requests\n'
            f'import os\n'
            f'\n'
            f'BASE_URL = os.getenv("BASE_URL", "{fallback}")\n'
            f'\n'
            f'\n'
            f'@pytest.fixture(scope="module")\n'
            f'def api_client():\n'
            f'    """Shared requests session for all chain tests."""\n'
            f'    session = requests.Session()\n'
            f'    yield session\n'
            f'    session.close()\n'
        )

    def _generate_chain_test(self, chain: EndpointChain) -> str:
        """Generate one test function for a chain."""
        func_name = f'test_{chain.name}'
        lines = [
            '',
            '',
            f'def {func_name}(api_client):',
            f'    """{chain.description}"""',
            '',
        ]

        # Track variables captured by earlier steps
        available_vars: Dict[str, str] = {}

        for i, step in enumerate(chain.steps, 1):
            step_lines = self._generate_step(
                step=step,
                step_num=i,
                total=len(chain.steps),
                available_vars=available_vars,
            )
            lines.extend(step_lines)
            available_vars.update(step.captures)

        return '\n'.join(lines)

    def _generate_step(
        self,
        step: ChainStep,
        step_num: int,
        total: int,
        available_vars: Dict[str, str],
    ) -> List[str]:
        ep = step.endpoint
        lines = []

        lines.append(f'    # Step {step_num}/{total}: {ep.method} {ep.path}')

        # Build URL with path params substituted
        url_expr = self._build_url_expr(ep.path, step.uses)
        lines.append(f'    url = f"{url_expr}"')

        # Auth header injection
        auth_var = next(
            (var for var, loc in step.uses.items()
             if loc == 'header:Authorization'),
            None,
        )
        if auth_var:
            lines.append(
                f'    headers = {{"Authorization": f"Bearer {{{auth_var}}}"}}'
            )

        # Request body for mutating methods
        if ep.method in ('POST', 'PUT', 'PATCH'):
            lines.extend(self._build_payload_lines(ep))

        # HTTP call
        lines.append(self._build_call_line(ep, auth_var))

        # Assert status code
        expected = self._expected_statuses(ep)
        lines.append(f'    assert r.status_code in {expected}, \\')
        lines.append(
            f'        f"Step {step_num} {ep.method} {ep.path} '
            f'failed: {{r.status_code}} {{r.text}}"'
        )

        # Capture response fields
        if step.captures:
            lines.append('    data = r.json()')
            for resp_field, var_name in step.captures.items():
                if resp_field in self._TOKEN_NAMES:
                    # Try multiple common token key names
                    lines.append(
                        f'    {var_name} = ('
                        f'data.get("access_token") or '
                        f'data.get("token") or '
                        f'data.get("jwt"))'
                    )
                else:
                    lines.append(f'    {var_name} = data.get("{resp_field}")')
                lines.append(
                    f'    assert {var_name} is not None, \\'
                )
                lines.append(
                    f'        "Step {step_num}: response missing '
                    f'\'{resp_field}\' field"'
                )

        # Round-trip check: GET should return the same id we created
        if ep.method == 'GET' and step.uses and step.captures:
            for var_name, loc in step.uses.items():
                if 'path:' in loc and var_name in available_vars:
                    lines.append(
                        f'    assert data.get("id") == {var_name} or \\'
                    )
                    lines.append(
                        f'        data.get("id") is None, \\'
                    )
                    lines.append(
                        f'        "GET returned different resource than expected"'
                    )

        lines.append('')   # blank line between steps
        return lines

    # ── URL building ──────────────────────────────────────────────────────────

    def _build_url_expr(self, path: str, uses: Dict[str, str]) -> str:
        """
        Build an f-string body with path params substituted.

        /pets/{petId} + uses={'pet_id': 'path:{petId}'} → {BASE_URL}/pets/{pet_id}
        """
        # Map path param names → variable names from uses dict
        param_to_var: Dict[str, str] = {}
        for var_name, loc in uses.items():
            m = re.match(r'path:\{(\w+)\}', loc)
            if m:
                param_to_var[m.group(1)] = var_name

        result = path
        for param, var in param_to_var.items():
            result = result.replace('{' + param + '}', '{' + var + '}')

        return '{BASE_URL}' + result

    # ── Payload building ──────────────────────────────────────────────────────

    def _build_payload_lines(self, ep: EndpointSpec) -> List[str]:
        """Build a payload dict from the endpoint's request body schema."""
        lines = ['    payload = {']

        rb = ep.request_body
        if rb:
            props = rb.get('schema', {}).get('properties', {})
            for field_name, field_info in props.items():
                value = self._example_value(
                    field_name,
                    field_info.get('type', 'string'),
                    field_info.get('example'),
                )
                lines.append(f'        "{field_name}": {value},')
        else:
            lines.append('        # no request body schema found in spec')

        lines.append('    }')
        return lines

    # ── Call building ─────────────────────────────────────────────────────────

    def _build_call_line(self, ep: EndpointSpec, auth_var: Optional[str]) -> str:
        method = ep.method.lower()
        headers_arg = ', headers=headers' if auth_var else ''
        if ep.method in ('POST', 'PUT', 'PATCH'):
            return f'    r = api_client.{method}(url, json=payload{headers_arg})'
        else:
            return f'    r = api_client.{method}(url{headers_arg})'

    def _expected_statuses(self, ep: EndpointSpec) -> str:
        if ep.method == 'POST':
            return '[200, 201]'
        if ep.method == 'DELETE':
            return '[200, 204]'
        return '[200]'

    # ── Value generation ──────────────────────────────────────────────────────

    _TOKEN_NAMES = frozenset({
        'token', 'access_token', 'accessToken',
        'jwt', 'refresh_token', 'id_token',
    })

    def _example_value(
        self, field_name: str, field_type: str, example: Any
    ) -> str:
        """Return a Python literal suitable for a request payload field."""
        if example is not None:
            if isinstance(example, str):
                return f'"{example}"'
            return str(example)

        name = field_name.lower()
        if 'email' in name:
            return '"test@example.com"'
        if 'password' in name or 'pass' in name:
            return '"change-me"'
        if 'name' in name:
            return f'"Test {field_name.capitalize()}"'
        if 'tag' in name:
            return '"test"'
        if 'url' in name:
            return '"https://example.com"'
        if 'phone' in name:
            return '"+15550000001"'

        if field_type in ('integer', 'int'):
            return '1'
        if field_type in ('number', 'float'):
            return '1.0'
        if field_type == 'boolean':
            return 'True'
        if field_type == 'array':
            return '[]'
        if field_type == 'object':
            return '{}'

        return f'"{field_name}_test"'
