"""
failure_analyzer.py — AI-powered pytest failure analysis

Runs pytest, captures failures, and sends each one to Claude for a
structured diagnosis: severity, likely cause, and recommended fix.

Public API:

    analyzer = FailureAnalyzer()

    # Option A: run pytest and capture failures in one step
    output, exit_code = analyzer.run_pytest(["test_output/test_pets.py"])
    failures = analyzer.parse_failures(output)

    # Option B: parse saved pytest output
    failures = analyzer.parse_failures(open("pytest_output.txt").read())

    # Analyze (pass the agent's _call_ai function, or None for mock)
    analyses = analyzer.analyze_all(failures, call_ai_fn=agent._call_ai)

    # Pretty-print
    print(analyzer.format_report(analyses))
"""

from __future__ import annotations

import re
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable, List, Optional


# ── Data classes ──────────────────────────────────────────────────────────────

@dataclass
class FailureRecord:
    """A single pytest failure extracted from test output."""
    test_id: str            # e.g. "test_output/test_pets.py::test_createPet_success"
    test_name: str          # e.g. "test_createPet_success"
    test_file: str          # e.g. "test_output/test_pets.py"
    error_type: str         # e.g. "AssertionError", "ConnectionError"
    short_message: str      # The E-prefixed line(s) from pytest output
    traceback: str          # Full traceback block
    captured_stdout: str = ""   # Any captured print output
    captured_stderr: str = ""


@dataclass
class FailureAnalysis:
    """Claude's diagnosis of a single test failure."""
    test_name: str
    severity: str           # 'critical' | 'high' | 'medium' | 'low'
    likely_cause: str
    recommended_action: str
    code_suggestion: str = ""   # Optional corrected code snippet
    is_mock: bool = False   # True when generated by free-tier mock


# ── Main class ────────────────────────────────────────────────────────────────

class FailureAnalyzer:
    """
    Runs pytest, parses failures, and sends them to Claude for diagnosis.

    Designed to work standalone or as a component inside AITestingAgent.
    Gracefully degrades: if no call_ai_fn is provided (or the agent is
    on the free tier), mock analysis is returned.
    """

    # ── Public methods ─────────────────────────────────────────────────────

    def run_pytest(
        self,
        paths: List[str],
        extra_args: Optional[List[str]] = None,
        timeout: int = 120,
    ) -> tuple[str, int]:
        """
        Run pytest on the given paths and return (combined_output, exit_code).

        Args:
            paths:      List of files or directories to pass to pytest.
            extra_args: Additional pytest flags (e.g. ["-k", "test_create"]).
            timeout:    Maximum seconds before the subprocess is killed.

        Returns:
            Tuple of (stdout+stderr output as string, pytest exit code).
            Exit code 0 = all passed, 1 = some failed, 2 = interrupted,
            3 = internal error, 4 = usage error, 5 = no tests collected.
        """
        cmd = [
            sys.executable, "-m", "pytest",
            "--tb=long",         # Full tracebacks
            "--no-header",       # Cleaner output
            "-q",                # Less noise in the passing-test lines
        ] + (extra_args or []) + paths

        try:
            result = subprocess.run(
                cmd,
                capture_output=True,
                text=True,
                timeout=timeout,
            )
            combined = result.stdout + result.stderr
            return combined, result.returncode
        except subprocess.TimeoutExpired:
            return f"pytest timed out after {timeout}s", 4
        except FileNotFoundError:
            return "pytest not found. Install with: pip install pytest", 4

    def parse_failures(self, pytest_output: str) -> List[FailureRecord]:
        """
        Parse pytest --tb=long output and extract one FailureRecord per failure.

        Handles:
        - AssertionError with actual vs expected values
        - Exception tracebacks (ConnectionError, AttributeError, etc.)
        - Captured stdout/stderr blocks
        """
        failures: List[FailureRecord] = []

        # Split on the FAILURES section separator
        # pytest uses "====...==== FAILURES ====...====" then
        # "____...____  test_name  ____...____" per failure
        failures_block = self._extract_failures_block(pytest_output)
        if not failures_block:
            return failures

        # Split into individual failure blocks
        failure_sections = re.split(
            r'\n_{5,}\s+(.+?)\s+_{5,}\n',
            failures_block,
        )
        # failure_sections is [preamble, name1, body1, name2, body2, ...]
        it = iter(failure_sections[1:])  # skip preamble
        for name, body in zip(it, it):
            record = self._parse_failure_section(name.strip(), body)
            if record:
                failures.append(record)

        return failures

    def analyze_failure(
        self,
        failure: FailureRecord,
        call_ai_fn: Optional[Callable[[str], str]] = None,
    ) -> FailureAnalysis:
        """
        Analyze a single failure record.

        If call_ai_fn is provided and the response can be parsed, returns a
        Claude-generated analysis. Otherwise falls back to mock analysis.
        """
        if call_ai_fn is not None:
            try:
                prompt = self._build_prompt(failure)
                raw = call_ai_fn(prompt)
                analysis = self._parse_ai_response(raw, failure.test_name)
                if analysis:
                    return analysis
            except Exception:
                pass

        return self._mock_analyze(failure)

    def analyze_all(
        self,
        failures: List[FailureRecord],
        call_ai_fn: Optional[Callable[[str], str]] = None,
    ) -> List[FailureAnalysis]:
        """Analyze every failure in the list and return results in order."""
        return [self.analyze_failure(f, call_ai_fn) for f in failures]

    def format_report(self, analyses: List[FailureAnalysis]) -> str:
        """
        Render all analyses as a human-readable terminal report.

        Returns a multi-line string ready for print().
        """
        if not analyses:
            return "No failures to analyze."

        severity_order = {"critical": 0, "high": 1, "medium": 2, "low": 3}
        sorted_analyses = sorted(
            analyses,
            key=lambda a: severity_order.get(a.severity.lower(), 4),
        )

        lines = [
            "",
            "=" * 70,
            f"  FAILURE ANALYSIS REPORT  ({len(analyses)} failure(s))",
            "=" * 70,
        ]

        for i, a in enumerate(sorted_analyses, 1):
            severity_label = a.severity.upper()
            mock_tag = " [MOCK — add ANTHROPIC_API_KEY for AI analysis]" if a.is_mock else ""

            lines += [
                "",
                f"  [{i}] {a.test_name}",
                f"  {'─' * 66}",
                f"  Severity  : {severity_label}{mock_tag}",
                f"  Cause     : {a.likely_cause}",
                f"  Fix       : {a.recommended_action}",
            ]

            if a.code_suggestion:
                lines += [
                    "  Suggestion:",
                ]
                for code_line in a.code_suggestion.splitlines():
                    lines.append(f"      {code_line}")

        lines += ["", "=" * 70, ""]
        return "\n".join(lines)

    def format_json(self, analyses: List[FailureAnalysis]) -> list:
        """Return analyses as a list of dicts (for JSON export or CI)."""
        return [
            {
                "test_name": a.test_name,
                "severity": a.severity,
                "likely_cause": a.likely_cause,
                "recommended_action": a.recommended_action,
                "code_suggestion": a.code_suggestion,
                "is_mock": a.is_mock,
            }
            for a in analyses
        ]

    # ── Prompt construction ────────────────────────────────────────────────

    def _build_prompt(self, failure: FailureRecord) -> str:
        """Build the Claude diagnostic prompt for a single failure."""
        stdout_section = ""
        if failure.captured_stdout.strip():
            stdout_section = (
                f"\nCAPTURED STDOUT:\n{failure.captured_stdout.strip()}\n"
            )

        return f"""You are a senior test engineer diagnosing a pytest failure.
Provide a concise, actionable analysis. Return ONLY valid JSON — no prose, no markdown fences.

TEST: {failure.test_name}
FILE: {failure.test_file}
ERROR TYPE: {failure.error_type}

FAILURE MESSAGE:
{failure.short_message.strip()}

TRACEBACK:
{failure.traceback.strip()}{stdout_section}

Return JSON with exactly these keys:
{{
  "severity": "critical" | "high" | "medium" | "low",
  "likely_cause": "1-3 sentence explanation of why this test failed",
  "recommended_action": "Specific, actionable fix for this failure",
  "code_suggestion": "Optional corrected code snippet, or empty string"
}}

Severity guidelines:
- critical: auth failures, data corruption, security assertions failing
- high: wrong status code, missing required field, schema mismatch
- medium: assertion off by one, wrong format, unexpected empty response
- low: test setup issue, flaky network, test data not seeded"""

    # ── AI response parsing ────────────────────────────────────────────────

    def _parse_ai_response(
        self, raw: str, test_name: str
    ) -> Optional[FailureAnalysis]:
        """Extract JSON from Claude's response and map to FailureAnalysis."""
        import json

        # Strip markdown fences if present
        clean = re.sub(r'```(?:json)?\s*', '', raw).replace('```', '').strip()

        # Find first {...} block
        match = re.search(r'\{[\s\S]*\}', clean)
        if not match:
            return None

        try:
            data = json.loads(match.group(0))
        except (json.JSONDecodeError, ValueError):
            return None

        severity = data.get("severity", "medium").lower()
        if severity not in ("critical", "high", "medium", "low"):
            severity = "medium"

        return FailureAnalysis(
            test_name=test_name,
            severity=severity,
            likely_cause=data.get("likely_cause", "Unknown cause."),
            recommended_action=data.get("recommended_action", "Review the failure manually."),
            code_suggestion=data.get("code_suggestion", ""),
            is_mock=False,
        )

    # ── Mock analysis (free tier) ──────────────────────────────────────────

    # Patterns for classifying failures without Claude
    _PATTERNS: list[tuple[re.Pattern, str, str, str]] = [
        (
            re.compile(r'assert.*status_code.*==\s*(\d+).*\n.*AssertionError.*(\d+)\s*==\s*\d+', re.S),
            "high",
            "The API returned an unexpected HTTP status code. "
            "The test expected one code but received another.",
            "Verify the endpoint contract. Check if auth headers, "
            "request body, or base URL are correct.",
        ),
        (
            re.compile(r'ConnectionError|ConnectionRefused|Failed to establish'),
            "critical",
            "The test could not connect to the API server. "
            "The server may not be running or the BASE_URL is incorrect.",
            "Start the API server, check BASE_URL, and verify network access.",
        ),
        (
            re.compile(r'Timeout|ReadTimeout|ConnectTimeout'),
            "high",
            "The API request timed out. The server is reachable but not responding in time.",
            "Increase the request timeout or investigate server-side latency.",
        ),
        (
            re.compile(r'404'),
            "high",
            "The endpoint returned 404 Not Found. "
            "The path may be incorrect or the resource does not exist.",
            "Verify the endpoint path in the spec matches the running API. "
            "Check if path parameters (IDs) are valid.",
        ),
        (
            re.compile(r'401|403|Unauthorized|Forbidden'),
            "critical",
            "Authentication or authorization failure. "
            "The request was rejected by the server due to missing or invalid credentials.",
            "Add the required auth header or token to the api_client fixture.",
        ),
        (
            re.compile(r'KeyError|assert\s+["\'](\w+)["\']\s+in'),
            "medium",
            "A required field is missing from the response body. "
            "The API contract may differ from the spec.",
            "Print response.json() in the test to see the actual response shape, "
            "then update the assertion to match.",
        ),
        (
            re.compile(r'JSONDecodeError|json\.decoder'),
            "high",
            "The response body is not valid JSON. "
            "The server may be returning HTML (error page) or plain text.",
            "Print response.text to inspect the raw body. "
            "Check if the Content-Type header is application/json.",
        ),
        (
            re.compile(r'AssertionError'),
            "medium",
            "An assertion failed. The actual value did not match the expected value.",
            "Review the traceback to identify what was expected vs. received "
            "and update the assertion or fix the API response.",
        ),
    ]

    def _mock_analyze(self, failure: FailureRecord) -> FailureAnalysis:
        """
        Rule-based analysis for free tier.
        Matches error patterns and returns a relevant diagnosis.
        """
        combined = failure.traceback + "\n" + failure.short_message

        for pattern, severity, cause, action in self._PATTERNS:
            if pattern.search(combined):
                return FailureAnalysis(
                    test_name=failure.test_name,
                    severity=severity,
                    likely_cause=cause,
                    recommended_action=action,
                    code_suggestion="",
                    is_mock=True,
                )

        # Default fallback
        return FailureAnalysis(
            test_name=failure.test_name,
            severity="medium",
            likely_cause=(
                f"The test raised {failure.error_type}. "
                "Review the traceback for details."
            ),
            recommended_action=(
                "Add ANTHROPIC_API_KEY for AI-powered root cause analysis "
                "with specific fix recommendations."
            ),
            code_suggestion="",
            is_mock=True,
        )

    # ── Pytest output parsing ──────────────────────────────────────────────

    def _extract_failures_block(self, output: str) -> str:
        """Extract everything between the FAILURES header and the short summary."""
        # Match "=== FAILURES ===" or "=== short test summary info ==="
        start = re.search(r'={5,}\s+FAILURES\s+={5,}', output)
        if not start:
            return ""

        # End at the short summary or errors section
        end = re.search(
            r'\n={5,}\s+(?:short test summary info|ERRORS)\s+={5,}',
            output[start.end():],
        )
        if end:
            return output[start.end(): start.end() + end.start()]
        return output[start.end():]

    def _parse_failure_section(
        self, test_name: str, body: str
    ) -> Optional[FailureRecord]:
        """Parse a single failure block into a FailureRecord."""
        # Section headers from pytest can be either:
        #   "path/to/test_foo.py::test_bar"  (full id)
        #   "test_bar"                        (name only)
        if "::" in test_name:
            file_part, fn_name = test_name.rsplit("::", 1)
        else:
            fn_name = test_name
            # Try to extract file from the last "path.py:line: ErrorType" line in body
            file_match = re.search(
                r'([\w/\\.\-]+\.py):\d+:', body
            )
            file_part = file_match.group(1) if file_match else ""

        # Determine error type from the "E  SomeError" lines
        error_lines = re.findall(r'^E\s+(.+)$', body, re.MULTILINE)
        error_type = "Error"
        if error_lines:
            first_e = error_lines[0].strip()
            m = re.match(r'([A-Za-z]+(?:Error|Exception|Warning))', first_e)
            if m:
                error_type = m.group(1)
            elif "assert" in first_e.lower():
                error_type = "AssertionError"

        short_message = "\n".join(error_lines[:5]) if error_lines else ""

        # Extract captured output sections
        stdout_match = re.search(
            r'-+ Captured stdout call -+\n(.*?)(?:\n-+ |$)', body, re.DOTALL
        )
        captured_stdout = stdout_match.group(1).strip() if stdout_match else ""

        stderr_match = re.search(
            r'-+ Captured stderr call -+\n(.*?)(?:\n-+ |$)', body, re.DOTALL
        )
        captured_stderr = stderr_match.group(1).strip() if stderr_match else ""

        # Traceback = body minus captured-output sections
        traceback = re.sub(
            r'-+ Captured (?:stdout|stderr) call -+.*?(?=\n-+ |\Z)',
            '',
            body,
            flags=re.DOTALL,
        ).strip()

        return FailureRecord(
            test_id=test_name,
            test_name=fn_name,
            test_file=file_part,
            error_type=error_type,
            short_message=short_message,
            traceback=traceback[:3000],  # cap to avoid huge prompts
            captured_stdout=captured_stdout,
            captured_stderr=captured_stderr,
        )
