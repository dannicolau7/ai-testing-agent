"""
finding_tests.py — turn the audit's findings into tests that prove or clear them.

The audit reads source, so its findings are evidence: "this route shows no access check"
may be wrong if the check lives somewhere the audit cannot see. This module writes one
pytest test for each finding that a request can settle. Run against a test environment:

- the test FAILS  → the fault is real, and the failure message says what happened;
- the test PASSES → the audit's finding was a false alarm, or the fault has been fixed;
- the test is SKIPPED → it was not run, and says what it needs. Skipped is never passed.

Three kinds of finding can be tested this way:

    exists             the route answers at all, instead of "not found" or "method not allowed"
    refuses_anonymous  a caller who is not signed in is refused
    owner_only         a signed-in user is refused a row that belongs to someone else

Everything else (a missing foreign key, SQL built from values, a field the backend ignores)
is listed at the top of the generated file as needing a person or another kind of test.

    python cli.py audit path/to/app -r requirements.md --tests-out test_findings.py
    FINDINGS_BASE_URL=http://localhost:8000 pytest test_findings.py

Safety. These tests send real requests. A test of a route that changes data sends that
request, and if the fault is real the change happens: an unprotected DELETE deletes. Such
tests are skipped unless FINDINGS_ALLOW_WRITES=1 is set. Use a test environment only.
"""

from __future__ import annotations

import re
from typing import List, Tuple

MUTATING = {"POST", "PUT", "PATCH", "DELETE"}

_HEADER = '''"""Tests written from an application audit's findings.

Generated by `python cli.py audit ... --tests-out`. Do not edit; fix the application (or the
audit) and generate again.

A test here FAILS when the fault the audit reported is real. A pass means the finding was a
false alarm or has been fixed. A skip means the test was not run.

Run against a TEST environment only. These tests send real requests.

    FINDINGS_BASE_URL       where the application runs, e.g. http://localhost:8000
                            (include any prefix the routes are mounted under, e.g. /api)
    FINDINGS_ALLOW_WRITES   set to 1 to run tests that send POST, PUT, PATCH or DELETE.
                            If the fault is real, that request takes effect.
    FINDINGS_PATH_ID        the id put in path parameters (default 1)
    FINDINGS_USER_TOKEN     a bearer token for an ordinary signed-in user
    FINDINGS_OTHER_ID       the id of a row that belongs to a DIFFERENT user than the one
                            FINDINGS_USER_TOKEN signs in; needed by the ownership tests
"""
import os
import re

import pytest
import requests

BASE = os.environ.get("FINDINGS_BASE_URL", "").rstrip("/")
PATH_ID = os.environ.get("FINDINGS_PATH_ID", "1")
REFUSED = (401, 403)
PARAMETER = r"\\{[^}]*\\}|<[^>]*>|:[A-Za-z_][A-Za-z0-9_]*"


def _send(method, path, token=None, path_id=None):
    if not BASE:
        pytest.skip("FINDINGS_BASE_URL is not set")
    if method in ("POST", "PUT", "PATCH", "DELETE") and os.environ.get("FINDINGS_ALLOW_WRITES") != "1":
        pytest.skip("sends " + method + ", which may change data: set FINDINGS_ALLOW_WRITES=1 to run it")
    url = BASE + re.sub(PARAMETER, path_id or PATH_ID, path)
    headers = {"Authorization": "Bearer " + token} if token else {}
    return requests.request(method, url, headers=headers, timeout=20)


def _user_token():
    token = os.environ.get("FINDINGS_USER_TOKEN")
    if not token:
        pytest.skip("FINDINGS_USER_TOKEN is not set")
    return token
'''


def _slug(text: str) -> str:
    return re.sub(r"_+", "_", re.sub(r"\W+", "_", text.lower())).strip("_")


def generate(findings: list) -> Tuple[str, int, List[str]]:
    """(the test file, how many tests it holds, titles of findings no test was written for)."""
    tests: List[str] = []
    untested: List[str] = []
    seen = set()
    for finding in findings:
        check, method, path = finding.check, finding.method, finding.path
        if not check or not method or not path:
            untested.append(finding.title)
            continue
        key = (check, method, path)
        if key in seen:
            continue      # the same test settles both; its requirement ids were gathered below
        seen.add(key)
        requirements = list(dict.fromkeys(
            f.requirement for f in findings if (f.check, f.method, f.path) == key and f.requirement))
        name = f"test_{_slug(check)}_{_slug(method + ' ' + path)}"
        lines = []
        if requirements:
            lines.append(f"# Requirement: {', '.join(requirements)}")
        lines.append(f"def {name}():")
        lines.append(f"    \"\"\"Audit finding: {finding.title.replace(chr(92), '/').replace(chr(34), chr(39))}\"\"\"")
        if check == "exists":
            lines += [
                f"    response = _send({method!r}, {path!r}, os.environ.get(\"FINDINGS_USER_TOKEN\"))",
                f"    assert response.status_code not in (404, 405), (",
                f"        \"{method} {path} is not there: the server answered \" + str(response.status_code))",
            ]
        elif check == "refuses_anonymous":
            lines += [
                f"    response = _send({method!r}, {path!r})",
                f"    assert response.status_code in REFUSED, (",
                f"        \"{method} {path} let a caller through without signing in: \" + str(response.status_code))",
            ]
        elif check == "owner_only":
            lines += [
                "    token = _user_token()",
                "    other = os.environ.get(\"FINDINGS_OTHER_ID\")",
                "    if not other:",
                "        pytest.skip(\"FINDINGS_OTHER_ID is not set: the id of a row owned by a different user\")",
                f"    response = _send({method!r}, {path!r}, token, path_id=other)",
                "    assert response.status_code in (403, 404), (",
                f"        \"{method} {path} gave one user another user\'s row: \" + str(response.status_code))",
            ]
        else:
            untested.append(finding.title)
            continue
        tests.append("\n".join(lines))
    header = _HEADER
    if untested:
        header += "\n# Findings no test was written for. They need a person, or another kind of test:\n"
        header += "".join(f"#   - {title}\n" for title in dict.fromkeys(untested))
    body = "\n\n\n".join(tests)
    return header + ("\n\n" + body + "\n" if tests else ""), len(tests), list(dict.fromkeys(untested))
