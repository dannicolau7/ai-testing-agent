    def _print_tree(self):
        """Print directory tree of generated files."""
        def print_tree_recursive(path: Path, prefix: str = "", is_last: bool = True):
            if path.is_file():
                connector = "└── " if is_last else "├── "
                print(f"{prefix}{connector}{path.name}")
            elif path.is_dir():
                connector = "└── " if is_last else "├── "
                print(f"{prefix}{connector}{path.name}/")
                
                children = sorted(list(path.iterdir()))
                for i, child in enumerate(children):
                    is_last_child = i == len(children) - 1
                    extension = "    " if is_last else "│   "
                    print_tree_recursive(child, prefix + extension, is_last_child)
        
        print(f"\n{self.output_dir.name}/")
        children = sorted(list(self.output_dir.iterdir()))
        for i, child in enumerate(children):
            if child.name not in ['.git', '__pycache__', '.pytest_cache']:
                is_last = i == len(children) - 1
                print_tree_recursive(child, "", is_last)
