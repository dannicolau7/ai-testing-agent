    def _generate_realistic_data(self, params: Dict) -> Dict:
        """Generate realistic test data using Faker."""
        data = {}
        
        for param_name, param_info in params.items():
            if isinstance(param_info, dict):
                param_type = param_info.get('type', 'string').lower()
            else:
                param_type = 'string'
            
            # Generate realistic data based on field name and type
            if 'email' in param_name.lower():
                data[param_name] = self.faker.email()
            elif 'password' in param_name.lower():
                data[param_name] = self.faker.password(length=12, special_chars=True)
            elif 'name' in param_name.lower():
                data[param_name] = self.faker.name()
            elif 'phone' in param_name.lower():
                data[param_name] = self.faker.phone_number()
            elif 'address' in param_name.lower():
                data[param_name] = self.faker.address()
            elif 'url' in param_name.lower():
                data[param_name] = self.faker.url()
            elif param_type in ['int', 'integer']:
                data[param_name] = self.faker.random_int(1, 1000)
            elif param_type in ['float', 'number']:
                data[param_name] = round(self.faker.random.uniform(1.0, 1000.0), 2)
            elif param_type in ['bool', 'boolean']:
                data[param_name] = self.faker.boolean()
            else:
                data[param_name] = self.faker.word()
        
        return data
    
    def _format_dict(self, data: Dict, indent: int = 8) -> str:
        """Format dictionary for code generation."""
        indent_str = ' ' * indent
        items = []
        for key, value in data.items():
            if isinstance(value, str):
                items.append(f'"{key}": "{value}"')
            else:
                items.append(f'"{key}": {value}')
        return '{\n' + indent_str + f',\n{indent_str}'.join(items) + '\n' + ' ' * (indent - 4) + '}'
    
    def _generate_empty_params(self, params: Dict) -> str:
        """Generate empty parameter values."""
        items = [f'"{name}": ""' for name in list(params.keys())[:3]]
        return '\n            '.join(items)
    
    def _generate_null_params(self, params: Dict) -> str:
        """Generate null parameter values."""
        items = [f'"{name}": None' for name in list(params.keys())[:3]]
        return '\n            '.join(items)
    
    def _generate_long_params(self, params: Dict) -> str:
        """Generate very long parameter values."""
        items = [f'"{name}": "x" * 10000' for name in list(params.keys())[:2]]
        return '\n            '.join(items)
    
    def _generate_special_char_params(self, params: Dict) -> str:
        """Generate special character parameter values."""
        items = [f'"{name}": "!@#$%^&*()_+-=[]{{}}|;:,.<>?"' for name in list(params.keys())[:2]]
        return '\n            '.join(items)
    
    def _generate_unicode_params(self, params: Dict) -> str:
        """Generate Unicode parameter values."""
        items = [f'"{name}": "Hello 世界 🌍 Привет"' for name in list(params.keys())[:2]]
        return '\n            '.join(items)
    
    def _generate_test_scenarios(self, params: Dict) -> List:
        """Generate multiple test scenarios."""
        # Return list of tuples with test data + expected status
        return [
            ["valid@email.com", "SecurePass123!", 200],
            ["invalid-email", "weak", 400],
            ["", "", 400],
            ["test@example.com", "VeryLongPassword123!@#", 200],
            ["user@domain.co", "Pass123!", 200]
        ]
    
    def _format_scenario_values(self, scenario: List) -> List[str]:
        """Format scenario values for code."""
        formatted = []
        for val in scenario:
            if isinstance(val, str):
                formatted.append(f'"{val}"')
            else:
                formatted.append(str(val))
        return formatted
    
    def _get_scenario_param_names(self, params: Dict) -> List[str]:
        """Get parameter names for scenarios."""
        param_names = list(params.keys())[:2]  # Limit to 2 params for readability
        return param_names if param_names else ['param1', 'param2']
    
    def _format_params_from_names(self, params: Dict) -> str:
        """Format parameter assignment from names."""
        param_names = list(params.keys())[:2]
        if not param_names:
            return '"field": "value"'
        
        items = [f'"{name}": {name}' for name in param_names]
        return ',\n            '.join(items)
